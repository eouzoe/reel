    #[test]
    fn check_capability_rejects_narrowed_path_amplification() {
        let op = SlackOp::PostMessage { channel: "#other".into(), text: "x".into() };
        let result =
            SlackAdapter::<MockTransport>::check_capability(&op, &narrowed_cap_to_general());
        assert!(
            matches!(result, Err(SlackError::CapabilityDenied(_))),
            "expected CapabilityDenied, got {result:?}"
        );
    }

    #[test]
    fn check_capability_accepts_full_namespace_prefix() {
        let op = SlackOp::PostMessage { channel: "#general".into(), text: "x".into() };
        let result = SlackAdapter::<MockTransport>::check_capability(&op, &full_cap());
        result.unwrap_or_else(|e| panic!("expected ok, got {e}"));
    }

    // ─────────────────────────────────────────────────────────────────
    // Conformance proxy — t_004 "abort discards Class C"
    // ─────────────────────────────────────────────────────────────────
    //
    // The kernel-driven t_004 test lands with reel-core commit/abort.
    // Here we prove the static reachability claim: when a descriptor
    // is buffered but never passed to fire(), the transport remains
    // untouched. This is the I-002 enforcement at the adapter layer.

    #[tokio::test]
    async fn abort_path_never_invokes_transport_t_004_proxy() {
        let adapter = SlackAdapter::new(MockTransport::new());
        let descriptor =
            adapter.post_message("#general", "should never send").unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(adapter.transport().send_count(), 0, "no fire() means no transport.send()");
        assert!(matches!(descriptor, EffectDescriptor::C { .. }));
    }
