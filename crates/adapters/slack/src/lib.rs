//! Class C Slack messaging adapter for the reel protocol.
//!
//! `adapter-slack` is the **demo Class C adapter** that proves reel's
//! I-002 guarantee: a Slack message buffered by a View that is later
//! `abort`ed is never sent.
//!
//! # Overview
//!
//! [`SlackAdapter`] wraps a [`SlackTransport`] and offers three
//! constructor methods that produce
//! [`reel_spec::EffectDescriptor::C`] entries:
//!
//! | Method | Slack Web API |
//! |--------|---------------|
//! | [`SlackAdapter::post_message`]   | `chat.postMessage` |
//! | [`SlackAdapter::edit_message`]   | `chat.update`      |
//! | [`SlackAdapter::delete_message`] | `chat.delete`      |
//!
//! The descriptors are buffered by the kernel inside
//! `View.effects_hash`. At commit time the kernel calls
//! [`SlackAdapter::fire`] for each descriptor, supplying the View's
//! [`reel_spec::Capability`]. The adapter then validates the capability
//! and dispatches the operation through the transport.
//!
//! # Why not `impl ClassC`?
//!
//! `reel_effects::ClassC` is a **sealed in-process trait** (per
//! `effect-class-rules.md` § 5 + ADR-0025 ontology). External adapters
//! cannot — and do not need to — implement it directly. The kernel
//! constructs `reel_effects::BoxedC` from in-tree effect types
//! generated by the `#[reel::class_c]` proc-macro; this
//! adapter sits one level above that, mapping wire-format
//! [`reel_spec::EffectDescriptor::C`] descriptors back to live
//! [`SlackOp`] values at commit time.
//!
//! # Sealing & I-003 enforcement
//!
//! [`SlackAdapter::fire`] inspects the supplied capability and rejects
//! with E-009 ([`reel_spec::ReelError::CapabilityViolation`]) on any of:
//!
//! - `OpKind::FireC` ∉ `op_set`
//! - channel target outside `path_prefix`
//! - ttl semantics violated (current policy: `ttl == 0` ⇒ unbounded;
//!   non-zero ttl passes the static check; real wall-clock expiry is
//!   plumbed in a follow-up task)
//!
//! See `SlackAdapter::check_capability` for the source of truth.
//!
//! # Testing
//!
//! All adapter-level tests use [`MockTransport`]. **No unit test
//! performs real HTTP**, per the discipline that the adapter must be
//! exerciseable without a Slack workspace. The real HTTP transport
//! will land behind a cargo feature in a follow-up task.
//!
//! # References
//!
//! - `spec/spec.md` § 5.7 (effect classes), § 10 (logging discipline).
//! - `spec/adapter-interface.md` (adapter trait shape).
//! - the design notes,
//!   `0006-effect-isolation-layers.md`,
//!   `0025-six-types-three-verbs-three-invariants.md`.
//! - the design notes.

